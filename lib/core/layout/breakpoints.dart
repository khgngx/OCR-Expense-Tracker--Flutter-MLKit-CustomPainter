class Breakpoints {
  Breakpoints._();

  /// At or above this width the shell switches from bottom bar to side rail.
  static const double desktop = 900;

  /// At or above this width of the real window the view-mode toggle appears.
  static const double toggleAvailable = 700;

  /// Side rail shows labels from this width.
  static const double extendedRail = 1200;

  /// Dashboard charts sit side by side from this content width.
  static const double dashboardTwoColumn = 760;
}
